#!/usr/bin/env node
// Builds dist/: the public, static site. Landing page at /, the lab at /lab/, the blog at /blog/.
// An allowlist, not a copy of web/: the deploy page, the WalletConnect bundle and the local node's deployment.json
// stay out, and there is no /relay (that lives in scripts/serve.js, which a static host never runs). The hosted lab
// works on public testnets and has visitors pay for cosign() from their own browser wallet.
//
//   npm run site:build     compiles, exports the lab's bundles, checks the blog, then writes dist/
//   npx serve dist         or any static file server, to look at the result

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const WEB = join(repo, 'web');
const OUT = join(repo, 'dist');

// [published path, source]. Folders are copied whole.
const FILES = [
  ['index.html', join(WEB, 'index.html')],
  ['styles.css', join(WEB, 'styles.css')],
  ['theme.js', join(WEB, 'theme.js')],
  ['assets', join(WEB, 'assets')],
  ['lab', join(WEB, 'lab')],
  ['blog', join(WEB, 'blog')],
  // Generated by `npm run site:build` before this script runs (see package.json).
  ['deploy-bundle.json', join(WEB, 'deploy-bundle.json')],
  ['contract-source.json', join(WEB, 'contract-source.json')],
  ['vendor/ethers.umd.min.js', join(repo, 'node_modules', 'ethers', 'dist', 'ethers.umd.min.js')],
];

// Headers for hosts that read a _headers file (Cloudflare Pages, Netlify). The pages carry their CSP in a meta tag;
// framing can only be refused by a header.
const HEADERS = `/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
  Content-Security-Policy: frame-ancestors 'none'
  Permissions-Policy: camera=(), microphone=(), geolocation=()
`;

for (const [, src] of FILES) if (!existsSync(src)) throw new Error(`Missing ${src}. Run npm run site:build, which generates it.`);
const bundle = JSON.parse(readFileSync(join(WEB, 'deploy-bundle.json'), 'utf8'));
const source = JSON.parse(readFileSync(join(WEB, 'contract-source.json'), 'utf8'));
if (!bundle.abi || !bundle.runtimeBytecode) throw new Error('deploy-bundle.json lacks abi or runtimeBytecode');
if (source.runtimeBytecode && source.runtimeBytecode.toLowerCase() !== bundle.runtimeBytecode.toLowerCase())
  throw new Error('contract-source.json and deploy-bundle.json come from different builds');

rmSync(OUT, { recursive: true, force: true });
for (const [to, src] of FILES) {
  mkdirSync(dirname(join(OUT, to)), { recursive: true });
  cpSync(src, join(OUT, to), { recursive: true, filter: (f) => !f.endsWith('.gitkeep') });
}
writeFileSync(join(OUT, '_headers'), HEADERS);
console.log(`Site: dist/ written (Vestige ${bundle.address}). Serve it from any static host.`);
